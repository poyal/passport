import type { ITheme } from "@xterm/xterm";
export type ThemePreset = {
  id: string;
  name: string;
  source: string;
  theme: ITheme;
};
const ansi = [
  "black",
  "red",
  "green",
  "yellow",
  "blue",
  "magenta",
  "cyan",
  "white",
  "brightBlack",
  "brightRed",
  "brightGreen",
  "brightYellow",
  "brightBlue",
  "brightMagenta",
  "brightCyan",
  "brightWhite",
] as const;
function preset(
  id: string,
  name: string,
  source: string,
  bg: string,
  fg: string,
  colors: string[],
  cursor = fg,
): ThemePreset {
  return {
    id,
    name,
    source,
    theme: {
      background: bg,
      foreground: fg,
      cursor,
      cursorAccent: bg,
      selectionBackground: fg + "40",
      selectionInactiveBackground: fg + "25",
      ...Object.fromEntries(ansi.map((key, i) => [key, colors[i]])),
    },
  };
}
